import type { Product } from '@/lib/products';

/** Only fields needed for storefront variant resolution and cart display. */
export function projectChatProduct(product: Product): Product {
  return {
    id: product.id,
    merchant_id: product.merchant_id,
    name: product.name,
    description: '',
    status: product.status,
    slug: product.slug,
    price: product.price,
    compare_at_price: product.compare_at_price,
    manage_stock: product.manage_stock,
    inventory_tracking_policy: product.inventory_tracking_policy,
    effective_policy: product.effective_policy,
    stock: product.stock,
    stock_quantity: product.stock_quantity,
    image: product.image,
    imageLarge: product.imageLarge,
    imageHint: product.imageHint,
    brand: product.brand,
    gtin: '',
    mpn: '',
    category: product.category,
    category_slug: product.category_slug,
    has_variants: product.has_variants,
    variant_model: product.variant_model,
    default_variant_id: product.default_variant_id,
    condition: product.condition,
    available_conditions: product.available_conditions,
    has_condition_offers: product.has_condition_offers,
    offers: product.offers?.map((offer) => ({
      id: offer.id,
      condition: offer.condition,
      price: offer.price,
      stock_quantity: offer.stock_quantity,
      images: offer.images,
    })),
    variants: product.variants?.map((variant) => ({
      id: variant.id,
      product_id: variant.product_id,
      merchant_id: variant.merchant_id,
      attributes: variant.attributes,
      condition: variant.condition,
      price_override: variant.price_override,
      stock_quantity: variant.stock_quantity,
      inventory_tracking_policy: variant.inventory_tracking_policy,
      effective_policy: variant.effective_policy,
      available_units: variant.available_units,
      images: variant.images,
      primary_image: variant.primary_image,
    })),
  };
}
