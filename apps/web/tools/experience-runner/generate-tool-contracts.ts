import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';
import { z } from 'zod';
import { experienceToolResult } from '../../src/schemas/experience-tool-results';
import { experienceToolInputs } from '../../src/schemas/experience-tools';
export function experienceWireContracts() {
  return {
    inputs: Object.fromEntries(
      Object.entries(experienceToolInputs).map(([n, s]) => [
        n,
        {
          ...z.toJSONSchema(s, { unrepresentable: 'any', io: 'input' }),
          type: 'object',
        },
      ])
    ),
    output: {
      ...z.toJSONSchema(experienceToolResult, { io: 'input' }),
      type: 'object',
    },
  };
}
export function generateExperienceContracts(check = false) {
  const root = new URL('../../builder-mcp-server/', import.meta.url);
  const directory = new URL('experience-wire-inputs/', root);
  const contracts = experienceWireContracts();
  const names = Object.keys(contracts.inputs);
  const index = [
    '// Generated by generate-tool-contracts.ts.',
    ...[...names].sort().map((name) => `import ${name} from './${name}.json';`),
    '',
    'export default {',
    ...names.map((name) => `  ${name},`),
    '};',
    '',
  ].join('\n');
  const files = [
    [new URL('experience-contracts.json', root), contracts.output],
    ...Object.entries(contracts.inputs).map(
      ([name, schema]) => [new URL(`${name}.json`, directory), schema] as const
    ),
    [new URL('index.ts', directory), index],
  ] as const;
  function assertFileLength(path: URL, content: string) {
    if (content.trimEnd().split('\n').length > 300)
      throw Error(`Experience contract exceeds 300 lines at ${path.pathname}`);
  }
  if (!check) mkdirSync(directory, { recursive: true });
  for (const [path, schema] of files) {
    const generated =
      typeof schema === 'string'
        ? schema
        : `${JSON.stringify(schema, null, 2)}\n`;
    assertFileLength(path, generated);
    if (!check) {
      writeFileSync(path, generated);
      continue;
    }
    const current = readFileSync(path, 'utf8');
    assertFileLength(path, current);
    const matches =
      typeof schema === 'string'
        ? current === schema
        : JSON.stringify(JSON.parse(current)) === JSON.stringify(schema);
    if (!matches) throw Error(`Experience contracts drift at ${path.pathname}`);
  }
}
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href)
  generateExperienceContracts(process.argv.includes('--check'));
