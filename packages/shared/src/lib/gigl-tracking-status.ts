function normalizeProviderStatus(value: string): string {
  return value
    .trim()
    .replace(/([a-z0-9])([A-Z])/g, '$1_$2')
    .replace(/[^a-z0-9]+/gi, '_')
    .replace(/^_+|_+$/g, '')
    .toUpperCase();
}

export function mapKnownGiglStatus(
  value: string
): ShipmentTrackingStatus | null {
  return GIGL_STATUS_MAP[normalizeProviderStatus(value)] ?? null;
}
